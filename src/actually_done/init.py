"""`actually-done init`: scaffold the files a repo needs to run both tiers for real -
the CI workflow, CODEOWNERS entries for grader paths, the oracle directory, an
AGENTS.md rules block imported into CLAUDE.md, and `[tool.actually-done]` defaults.

Never overwrites an existing file's content unless `force=True`. CLAUDE.md and
pyproject.toml are the two exceptions: this only ever appends what's missing from
them, so re-running `init` is always safe regardless of `force`.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path

_PLACEHOLDER_OWNER = "@YOUR-GITHUB-USERNAME"
_CLAUDE_MD_IMPORT = "@AGENTS.md"
_PYPROJECT_SECTION_MARKER = "[tool.actually-done]"

_CODEOWNERS_PATTERNS = [
    "conftest.py",
    "**/conftest.py",
    "pytest.ini",
    "setup.cfg",
    "**/*.pth",
    "sitecustomize.py",
    "jest.config.*",
    "vitest.config.*",
    "**/__mocks__/**",
    "package.json",
    "package-lock.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "requirements*.txt",
    "pyproject.toml",
    "poetry.lock",
    "uv.lock",
    ".github/",
    ".verify/",
    "AGENTS.md",
    "CLAUDE.md",
    ".claude/",
    ".cursor/",
    ".codex/",
]


@dataclass(frozen=True)
class InitReport:
    written: list[str] = field(default_factory=list)
    appended: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)


def run_init(repo_root: Path, force: bool = False) -> InitReport:
    report = InitReport()

    _write_template(
        repo_root / ".github" / "workflows" / "actually-done.yml", "workflow.yml", force, report
    )
    _write_codeowners(repo_root / "CODEOWNERS", force, report)
    _ensure_oracle_dir(repo_root / "tests" / "oracle", report)
    _write_template(repo_root / "AGENTS.md", "AGENTS.md", force, report)
    _append_claude_md_import(repo_root / "CLAUDE.md", report)
    _append_pyproject_defaults(repo_root / "pyproject.toml", report)

    return report


def _template_text(name: str) -> str:
    return (resources.files("actually_done") / "templates" / name).read_text(encoding="utf-8")


def _write_template(dest: Path, template_name: str, force: bool, report: InitReport) -> None:
    if dest.exists() and not force:
        report.skipped.append(str(dest))
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(_template_text(template_name), encoding="utf-8")
    report.written.append(str(dest))


def _write_codeowners(dest: Path, force: bool, report: InitReport) -> None:
    if dest.exists() and not force:
        report.skipped.append(str(dest))
        return
    header = (
        "# Generated by `actually-done init`.\n"
        f"# Replace {_PLACEHOLDER_OWNER} with yourself or a team: these are the paths a\n"
        "# grader-tampering PR would touch, so Code Owner review gates them\n"
        "# (solution.md, problem 3).\n"
    )
    lines = [f"{pattern} {_PLACEHOLDER_OWNER}" for pattern in _CODEOWNERS_PATTERNS]
    dest.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    report.written.append(str(dest))


def _ensure_oracle_dir(dest: Path, report: InitReport) -> None:
    gitkeep = dest / ".gitkeep"
    if gitkeep.exists():
        report.skipped.append(str(gitkeep))
        return
    dest.mkdir(parents=True, exist_ok=True)
    gitkeep.write_text("", encoding="utf-8")
    report.written.append(str(gitkeep))


def _append_claude_md_import(dest: Path, report: InitReport) -> None:
    if dest.is_file():
        text = dest.read_text(encoding="utf-8")
        if _CLAUDE_MD_IMPORT in text:
            report.skipped.append(str(dest))
            return
        new_text = text.rstrip("\n") + f"\n\n{_CLAUDE_MD_IMPORT}\n"
    else:
        new_text = f"{_CLAUDE_MD_IMPORT}\n"
    dest.write_text(new_text, encoding="utf-8")
    report.appended.append(str(dest))


def _append_pyproject_defaults(dest: Path, report: InitReport) -> None:
    if dest.is_file():
        text = dest.read_text(encoding="utf-8")
        if _PYPROJECT_SECTION_MARKER in text:
            report.skipped.append(str(dest))
            return
        new_text = text.rstrip("\n") + "\n\n" + _default_pyproject_section()
    else:
        new_text = _default_pyproject_section()
    dest.write_text(new_text, encoding="utf-8")
    report.appended.append(str(dest))


def _default_pyproject_section() -> str:
    return '[tool.actually-done]\nunit_test_path = "tests/unit"\nfast_timeout_seconds = 50\n'
