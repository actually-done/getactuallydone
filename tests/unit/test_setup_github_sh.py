"""scripts/setup_github.sh: the ruleset JSON (--dry-run, no API calls) and the
CODEOWNERS placeholder replacement. Every test runs against an isolated copy of
the files the script touches under tmp_path - never the real repo's own
.github/workflows/actually-done.yml or CODEOWNERS.
"""

from __future__ import annotations

import json
import platform
import shutil
import subprocess
from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parents[2]
_SCRIPT = _REPO_ROOT / "scripts" / "setup_github.sh"
_REAL_WORKFLOW = _REPO_ROOT / ".github" / "workflows" / "actually-done.yml"


def _find_working_bash() -> str | None:
    candidates = []
    if platform.system() == "Windows":
        candidates += [
            r"C:\Program Files\Git\usr\bin\bash.exe",
            r"C:\Program Files\Git\bin\bash.exe",
        ]
    found = shutil.which("bash")
    if found:
        candidates.append(found)
    for candidate in candidates:
        try:
            subprocess.run([candidate, "--version"], capture_output=True, timeout=10, check=True)
            return candidate
        except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
            continue
    return None


_BASH = _find_working_bash()
pytestmark = pytest.mark.skipif(_BASH is None, reason="requires a working bash")


@pytest.fixture
def sandbox(tmp_path: Path) -> Path:
    """An isolated copy of just what the script touches: the workflow file (for
    deriving the status-check name) and a CODEOWNERS with the real placeholder.
    """
    workflows = tmp_path / ".github" / "workflows"
    workflows.mkdir(parents=True)
    shutil.copy(_REAL_WORKFLOW, workflows / "actually-done.yml")
    (tmp_path / "CODEOWNERS").write_text(
        "# Generated by `actually-done init`.\n"
        "conftest.py @YOUR-GITHUB-USERNAME\n"
        "pytest.ini @YOUR-GITHUB-USERNAME\n",
        encoding="utf-8",
    )
    scripts_dir = tmp_path / "scripts"
    scripts_dir.mkdir()
    shutil.copy(_SCRIPT, scripts_dir / "setup_github.sh")
    return tmp_path


def _run(sandbox: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [_BASH, str(sandbox / "scripts" / "setup_github.sh"), *args],
        cwd=sandbox,
        capture_output=True,
        text=True,
        timeout=30,
    )


def test_dry_run_prints_valid_ruleset_json(sandbox: Path) -> None:
    result = _run(sandbox, "actually-done/actually-done", "test-user", "--dry-run")
    assert result.returncode == 0, result.stderr

    payload = json.loads(result.stdout)
    assert payload["target"] == "branch"
    assert payload["enforcement"] == "active"
    assert payload["bypass_actors"] == [
        {"actor_type": "User", "actor_id": 0, "bypass_mode": "pull_request"}
    ]
    assert payload["conditions"] == {
        "ref_name": {"include": ["~DEFAULT_BRANCH"], "exclude": []}
    }

    rule_types = [r["type"] for r in payload["rules"]]
    assert rule_types == [
        "pull_request",
        "required_status_checks",
        "non_fast_forward",
        "deletion",
    ]

    pr_rule = payload["rules"][0]["parameters"]
    assert pr_rule["required_approving_review_count"] == 1
    assert pr_rule["dismiss_stale_reviews_on_push"] is True
    assert pr_rule["require_code_owner_review"] is True
    assert pr_rule["require_last_push_approval"] is True

    status_rule = payload["rules"][1]["parameters"]
    assert status_rule["strict_required_status_checks_policy"] is True
    assert status_rule["required_status_checks"] == [{"context": "actually-done full tier"}]


def test_dry_run_never_invokes_gh_at_all(sandbox: Path) -> None:
    """--dry-run must succeed even when `gh` would fail if called - proving it
    never shells out to the API, not just that it happens to print the right
    thing when gh *is* available. A stub `gh` that errors loudly, placed first
    on PATH, proves this the same way dropping `gh` from PATH entirely would -
    without removing whole PATH directories, which on a stock Linux runner can
    hold `gh` bundled alongside `dirname`/`git`/coreutils in the same directory
    (e.g. /usr/bin), so stripping any directory containing `gh` there breaks
    far more than just `gh` itself.
    """
    import os

    fake_bin = sandbox / "fakebin"
    fake_bin.mkdir()
    _make_stub(fake_bin, "gh", 'echo "gh should never be invoked by --dry-run" >&2\nexit 1')
    env = dict(os.environ)
    env["PATH"] = os.pathsep.join([str(fake_bin), env.get("PATH", "")])
    script = str(sandbox / "scripts" / "setup_github.sh")
    result = subprocess.run(
        [_BASH, script, "owner/repo", "test-user", "--dry-run"],
        cwd=sandbox,
        capture_output=True,
        text=True,
        env=env,
        timeout=30,
    )
    assert result.returncode == 0, result.stderr
    assert "Creating ruleset" not in result.stderr
    assert "should never be invoked" not in result.stderr
    json.loads(result.stdout)  # still valid JSON


def test_dry_run_bypass_actor_placeholder_is_explained(sandbox: Path) -> None:
    """--dry-run can't resolve a real user id without calling `gh` (which it must
    never do), so it shows a placeholder and must say so, not leave it looking
    like a real id.
    """
    result = _run(sandbox, "owner/repo", "test-user", "--dry-run")
    assert "Bypass actor: @test-user" in result.stderr
    assert "never calls" in result.stderr
    payload = json.loads(result.stdout)
    assert payload["bypass_actors"] == [
        {"actor_type": "User", "actor_id": 0, "bypass_mode": "pull_request"}
    ]


def _make_stub(bin_dir: Path, name: str, body: str) -> None:
    stub = bin_dir / name
    stub.write_text(f"#!/usr/bin/env bash\n{body}\n", encoding="utf-8")
    stub.chmod(0o755)


def test_real_run_resolves_bypass_actor_id_via_gh(sandbox: Path) -> None:
    """A real (non-dry-run) call must look up GITHUB_USERNAME's numeric id via
    `gh api users/<username>` and put that real id - not a placeholder - into
    the bypass_actors entry it sends and prints back.
    """
    import os

    fake_bin = sandbox / "fakebin"
    fake_bin.mkdir()
    _make_stub(
        fake_bin,
        "gh",
        """
case "$*" in
  *"users/test-user"*)
    echo 424242
    ;;
  *"--method POST"*)
    cat >/dev/null
    echo 999
    ;;
  *"rulesets/999"*)
    echo '{"id": 999, "bypass_actors":'
    echo '  [{"actor_type": "User", "actor_id": 424242, "bypass_mode": "pull_request"}]}'
    ;;
  *)
    echo "unexpected gh invocation: $*" >&2
    exit 1
    ;;
esac
""",
    )
    env = dict(os.environ)
    env["PATH"] = os.pathsep.join([str(fake_bin), env.get("PATH", "")])
    script = str(sandbox / "scripts" / "setup_github.sh")
    result = subprocess.run(
        [_BASH, script, "owner/repo", "test-user"],
        cwd=sandbox,
        capture_output=True,
        text=True,
        env=env,
        timeout=30,
    )
    assert result.returncode == 0, result.stderr
    assert "424242" in result.stdout
    assert "Resolving GitHub user id for @test-user" in result.stderr


def test_real_run_errors_when_user_lookup_fails(sandbox: Path) -> None:
    import os

    fake_bin = sandbox / "fakebin"
