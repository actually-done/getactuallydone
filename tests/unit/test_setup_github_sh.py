"""scripts/setup_github.sh: the ruleset JSON (--dry-run, no API calls) and the
CODEOWNERS placeholder replacement. Every test runs against an isolated copy of
the files the script touches under tmp_path - never the real repo's own
.github/workflows/actually-done.yml or CODEOWNERS.
"""

from __future__ import annotations

import json
import platform
import shutil
import subprocess
from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parents[2]
_SCRIPT = _REPO_ROOT / "scripts" / "setup_github.sh"
_REAL_WORKFLOW = _REPO_ROOT / ".github" / "workflows" / "actually-done.yml"


def _find_working_bash() -> str | None:
    candidates = []
    if platform.system() == "Windows":
        candidates += [
            r"C:\Program Files\Git\usr\bin\bash.exe",
            r"C:\Program Files\Git\bin\bash.exe",
        ]
    found = shutil.which("bash")
    if found:
        candidates.append(found)
    for candidate in candidates:
        try:
            subprocess.run([candidate, "--version"], capture_output=True, timeout=10, check=True)
            return candidate
        except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
            continue
    return None


_BASH = _find_working_bash()
pytestmark = pytest.mark.skipif(_BASH is None, reason="requires a working bash")


@pytest.fixture
def sandbox(tmp_path: Path) -> Path:
    """An isolated copy of just what the script touches: the workflow file (for
    deriving the status-check name) and a CODEOWNERS with the real placeholder.
    """
    workflows = tmp_path / ".github" / "workflows"
    workflows.mkdir(parents=True)
    shutil.copy(_REAL_WORKFLOW, workflows / "actually-done.yml")
    (tmp_path / "CODEOWNERS").write_text(
        "# Generated by `actually-done init`.\n"
        "conftest.py @YOUR-GITHUB-USERNAME\n"
        "pytest.ini @YOUR-GITHUB-USERNAME\n",
        encoding="utf-8",
    )
    scripts_dir = tmp_path / "scripts"
    scripts_dir.mkdir()
    shutil.copy(_SCRIPT, scripts_dir / "setup_github.sh")
    return tmp_path


def _run(sandbox: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [_BASH, str(sandbox / "scripts" / "setup_github.sh"), *args],
        cwd=sandbox,
        capture_output=True,
        text=True,
        timeout=30,
    )


def test_dry_run_prints_valid_ruleset_json(sandbox: Path) -> None:
    result = _run(sandbox, "actually-done/getactuallydone", "test-user", "--dry-run")
    assert result.returncode == 0, result.stderr

    payload = json.loads(result.stdout)
    assert payload["target"] == "branch"
    assert payload["enforcement"] == "active"
    assert payload["bypass_actors"] == []
    assert payload["conditions"] == {
        "ref_name": {"include": ["~DEFAULT_BRANCH"], "exclude": []}
    }

    rule_types = [r["type"] for r in payload["rules"]]
    assert rule_types == [
        "pull_request",
        "required_status_checks",
        "non_fast_forward",
        "deletion",
    ]

    pr_rule = payload["rules"][0]["parameters"]
    assert pr_rule["required_approving_review_count"] == 1
    assert pr_rule["dismiss_stale_reviews_on_push"] is True
    assert pr_rule["require_code_owner_review"] is True
    assert pr_rule["require_last_push_approval"] is True

    status_rule = payload["rules"][1]["parameters"]
    assert status_rule["strict_required_status_checks_policy"] is True
    assert status_rule["required_status_checks"] == [{"context": "actually-done full tier"}]


def test_dry_run_never_invokes_gh_at_all(sandbox: Path) -> None:
    """--dry-run must succeed even when `gh` isn't on PATH at all - proving it
    never shells out to the API, not just that it happens to print the right
    thing when gh *is* available.
    """
    import os

    env = dict(os.environ)
    kept = [
        entry
        for entry in env.get("PATH", "").split(os.pathsep)
        if entry and not (Path(entry) / "gh").exists() and not (Path(entry) / "gh.exe").exists()
    ]
    env["PATH"] = os.pathsep.join(kept)
    script = str(sandbox / "scripts" / "setup_github.sh")
    result = subprocess.run(
        [_BASH, script, "owner/repo", "test-user", "--dry-run"],
        cwd=sandbox,
        capture_output=True,
        text=True,
        env=env,
        timeout=30,
    )
    assert result.returncode == 0, result.stderr
    assert "Creating ruleset" not in result.stderr
    json.loads(result.stdout)  # still valid JSON


def test_status_check_name_derived_from_real_workflow_job(sandbox: Path) -> None:
    result = _run(sandbox, "owner/repo", "someone", "--dry-run")
    assert 'Required status check context: "actually-done full tier"' in result.stderr


def test_status_check_override(sandbox: Path) -> None:
    result = _run(
        sandbox, "owner/repo", "someone", "--dry-run", "--status-check", "my-custom-check"
    )
    payload = json.loads(result.stdout)
    status_rule = payload["rules"][1]["parameters"]
    assert status_rule["required_status_checks"] == [{"context": "my-custom-check"}]


def test_replaces_codeowners_placeholder(sandbox: Path) -> None:
    _run(sandbox, "owner/repo", "test-user", "--dry-run")
    text = (sandbox / "CODEOWNERS").read_text(encoding="utf-8")
    assert "@YOUR-GITHUB-USERNAME" not in text
    assert "@test-user" in text
    assert text.count("@test-user") == 2  # both lines in the fixture


def test_strips_leading_at_from_username(sandbox: Path) -> None:
    _run(sandbox, "owner/repo", "@test-user", "--dry-run")
    text = (sandbox / "CODEOWNERS").read_text(encoding="utf-8")
    assert "@test-user" in text
    assert "@@test-user" not in text


def test_rerun_after_placeholder_already_replaced_is_a_clean_noop(sandbox: Path) -> None:
    first = _run(sandbox, "owner/repo", "test-user", "--dry-run")
    assert first.returncode == 0
    second = _run(sandbox, "owner/repo", "someone-else", "--dry-run")
    assert second.returncode == 0
    assert "already replaced, nothing to do" in second.stderr
    text = (sandbox / "CODEOWNERS").read_text(encoding="utf-8")
    assert "@test-user" in text  # not clobbered by the second run's different username


def test_missing_arguments_is_a_usage_error(sandbox: Path) -> None:
    result = _run(sandbox)
    assert result.returncode == 2


def test_malformed_repo_slug_is_a_usage_error(sandbox: Path) -> None:
    result = _run(sandbox, "not-a-slug", "test-user", "--dry-run")
    assert result.returncode == 2
    assert "owner/repo form" in result.stderr


def test_empty_username_is_a_usage_error(sandbox: Path) -> None:
    result = _run(sandbox, "owner/repo", "", "--dry-run")
    assert result.returncode == 2


def test_missing_workflow_file_without_override_is_an_error(tmp_path: Path) -> None:
    scripts_dir = tmp_path / "scripts"
    scripts_dir.mkdir()
    shutil.copy(_SCRIPT, scripts_dir / "setup_github.sh")
    (tmp_path / "CODEOWNERS").write_text("conftest.py @YOUR-GITHUB-USERNAME\n", encoding="utf-8")
    # No .github/workflows/actually-done.yml at all.
    result = _run(tmp_path, "owner/repo", "test-user", "--dry-run")
    assert result.returncode == 1
    assert "pass --status-check" in result.stderr


def test_status_check_override_works_without_a_workflow_file(tmp_path: Path) -> None:
    scripts_dir = tmp_path / "scripts"
    scripts_dir.mkdir()
    shutil.copy(_SCRIPT, scripts_dir / "setup_github.sh")
    (tmp_path / "CODEOWNERS").write_text("conftest.py @YOUR-GITHUB-USERNAME\n", encoding="utf-8")
    result = _run(
        tmp_path, "owner/repo", "test-user", "--dry-run", "--status-check", "whatever"
    )
    assert result.returncode == 0
    payload = json.loads(result.stdout)
    assert payload["rules"][1]["parameters"]["required_status_checks"] == [
        {"context": "whatever"}
    ]
